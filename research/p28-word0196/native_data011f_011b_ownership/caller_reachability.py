def shortest_path(edges, root, target, blocked=()):
    """A syntactic witness only; a missing bounded path is not global proof."""
    excluded = frozenset(blocked)
    if root in excluded or root not in edges or target not in edges:
        return None
    parents = {root: None}
    pending = deque([root])
    while pending:
        current = pending.popleft()
        if current == target:
            path = []
            while current is not None:
                path.append(current)
                current = parents[current]
            return list(reversed(path))
        for successor in edges[current]:
            if successor in edges and successor not in excluded and successor not in parents:
                parents[successor] = current
                pending.append(successor)
    return None


