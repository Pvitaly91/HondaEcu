def frame_layout(ssp):
    """Project architectural word addresses for an invented unsigned16 SSP."""
    if type(ssp) is not int or not 0 <= ssp <= 0xFFFF:
        raise ValueError('Unsigned16BitSSPRequired')
    slots = []
    for index, role in enumerate(('PC', 'A', 'LRB', 'PSW')):
        address = ((ssp - 2 * index) & 0xFFFF) & 0xFFFE
        slots.append({'role': role, 'wordAddress': address,
            'byteAddresses': [address, address + 1], 'widthBits': 16, 'value': None})
    after = (ssp - 8) & 0xFFFF
    reads = [{'step': index + 1, 'role': slot['role'],
        'sspBeforeRead': (after + 2 * (index + 1)) & 0xFFFF,
        'wordAddress': slot['wordAddress'], 'value': None}
        for index, slot in enumerate(reversed(slots))]
    return {'classification': 'InventedAddressAlgebra_NotCreatedOrObservedFrame',
        'incomingSSP': ssp, 'sspAfterEntry': after, 'sspAfterRti': (after + 8) & 0xFFFF,
        'entryWordSlots': slots, 'rtiWordReads': reads,
        'byteFootprint': sorted({byte for slot in slots for byte in slot['byteAddresses']}),
        'parityPreserved': (ssp & 1) == (after & 1),
        'physicalByteBusOrder': None, 'actualFrameCreator': None}


