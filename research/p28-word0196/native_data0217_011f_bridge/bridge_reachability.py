def postreturn_graphs():
    """Stop at the first unproved call, without inventing matching returns."""
    result = []
    for label, caller, returned, table, boundary, callee, next_pc in (
        ('P', 0x27D0, 0x27D3, POST_RETURN_P, 0x2810, 0x5BF5, 0x2813),
        ('Q', 0x4069, 0x406C, POST_RETURN_Q, 0x4165, 0x28AE, 0x4166),
    ):
        result.append({
            'route': label, 'producerCallerPC': caller, 'producerEntryPC': 0x5F45,
            'producerReturnPC': returned, 'matchingReturnCandidate': 0x60E4,
            'nodes': [{'pc': pc, 'form': form, 'edges': list(edges)} for pc, form, edges in table],
            'nodeCount': len(table), 'firstUnprovedCall': {
                'pc': boundary, 'form': 'CAL addr16' if label == 'P' else 'VCAL 3',
                'target': callee, 'conditionalReturnPC': next_pc,
                'matchingFrameEstablished': False, 'calleeEffectsReviewedByThisPrefix': False},
            'receiverOrCopyNodeInPrefix': False,
            'classification': 'ListedPostReturnPrefix_StopsAtUnprovedCall_NotExecution',
            'fullFutureLoopOrComputedPathsEstablished': False,
            'actualCpuExecutions': 0,
        })
    return deepcopy(result)


