"""Independent SOURCE-ONLY comparator controls; execution is root-gated.

These specimens are generated by the frozen pre-result reference/protocol, not
by Rust or by any observed runtime. Passing these tests alone cannot establish
production behavior, capability observation, or comparator sensitivity against
an actual runtime record. The root validator must perform those separate joins.
"""
from copy import deepcopy
from pathlib import Path
import sys
import unittest

SOURCE = Path(__file__).resolve()
HERE = SOURCE.parent
PUBLIC_ROOT = SOURCE.parents[2]
PRIVATE_DRAFT_ROOT = SOURCE.parents[4]
if HERE == PUBLIC_ROOT / "research/p28-word0196" and SOURCE.name == "production_optin_comparator_tests.py":
    ROOT = PUBLIC_ROOT
elif HERE == PRIVATE_DRAFT_ROOT / "private/reports/m2bp/draft" and SOURCE.name == "independent_comparator_review_tests.py":
    ROOT = PRIVATE_DRAFT_ROOT
else:
    raise RuntimeError("Only the reviewed public research path or private source draft is supported")
if not (ROOT / "rust/p28-slice-runner/Cargo.toml").is_file():
    raise RuntimeError("Exact repository-owned production source root required")
sys.path.insert(0, str(ROOT / "research/p28-word0196"))
sys.path.insert(0, str(HERE))

import production_optin_corpus as corpus
import production_optin_oracle as oracle
import production_optin_capability_oracle as capability_oracle


def changed(value):
    if type(value) is bool:
        return not value
    if type(value) is int:
        return value ^ 1
    if type(value) is str:
        return value + "_altered"
    if value is None:
        return False
    raise AssertionError("Only an explicit scalar mutation is permitted")


class IndependentComparatorReviewTests(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        cls.rows = corpus.build_corpus()
        cls.patterns = oracle.instrumentation.load_instrumentation_patterns(ROOT)
        cls.by_form = {}
        for row in cls.rows:
            if row["expected_admission"] == "Accepted":
                cls.by_form.setdefault(row["request"]["form"], row)
        if len(cls.by_form) != 16:
            raise AssertionError("Exactly sixteen independent positive form specimens required")
        cls.expected = {form: oracle.expected_case(row, cls.patterns)
                        for form, row in cls.by_form.items()}
        cls.capabilities = capability_oracle.expected_capabilities(cls.rows, cls.patterns)

    def assert_rejected(self, expected, actual, field=None):
        mismatch = oracle.difference(expected, actual)
        self.assertIsNotNone(mismatch)
        if field is not None:
            self.assertEqual(mismatch["field"], field)

    def test_exact_types_keys_and_array_order_have_no_normalization(self):
        specimen = self.expected["lb-a-page"]
        self.assertIsNone(oracle.difference(specimen, deepcopy(specimen)))
        for key in ("accepted", "firmware_ready", "pc_relocated"):
            actual = deepcopy(specimen)
            actual[key] = int(actual[key])
            self.assert_rejected(specimen, actual, "$." + key)
        actual = deepcopy(specimen)
        del actual["error"]
        self.assert_rejected(specimen, actual, "$.keys")
        actual = deepcopy(specimen)
        actual["undeclared_runtime_field"] = 0
        self.assert_rejected(specimen, actual, "$.keys")
        actual = deepcopy(specimen)
        actual["audit"]["program_events"].reverse()
        self.assert_rejected(specimen, actual)
        actual = deepcopy(specimen)
        actual["audit"]["raw_data_events"].pop()
        self.assert_rejected(specimen, actual, "$.audit.raw_data_events.length")

    def test_all_sixteen_form_decode_and_complete_state_projections_are_sensitive(self):
        for form, specimen in self.expected.items():
            with self.subTest(form=form, category="self-equality"):
                self.assertIsNone(oracle.difference(specimen, deepcopy(specimen)))
            for field in specimen["outcome"]["decoded"]:
                with self.subTest(form=form, category="decoded", field=field):
                    actual = deepcopy(specimen)
                    actual["outcome"]["decoded"][field] = changed(actual["outcome"]["decoded"][field])
                    self.assert_rejected(specimen, actual)
            for field in specimen["after"]["cpu"]:
                with self.subTest(form=form, category="cpu", field=field):
                    actual = deepcopy(specimen)
                    actual["after"]["cpu"][field] = changed(actual["after"]["cpu"][field])
                    self.assert_rejected(specimen, actual)
            for address in (0x80, 0xbf, 0x108, 0x109, 0x117, 0x124,
                            0x128, 0x12a, 0x18e, 0x18f, 0x196, 0x197, 0xfff):
                with self.subTest(form=form, category="raw-ram", address=address):
                    actual = deepcopy(specimen)
                    actual["after"]["ram"][address - 0x80] ^= 1
                    self.assert_rejected(specimen, actual)

    def test_actual_observation_schema_journal_and_counter_fields_are_compared(self):
        specimen = self.expected["rolb-page"]
        for journal in ("program_events", "data_events", "raw_data_events", "diagnostic_events"):
            self.assertTrue(specimen["audit"][journal])
            for field, value in specimen["audit"][journal][-1].items():
                if isinstance(value, (dict, list)):
                    continue
                with self.subTest(journal=journal, field=field):
                    actual = deepcopy(specimen)
                    actual["audit"][journal][-1][field] = changed(value)
                    self.assert_rejected(specimen, actual)
        for field in ("entry_pc", "current_pc", "program_base", "program_end_exclusive",
                      "program_sha256", "phase", "budget", "successful_retirements",
                      "step_calls", "execution_calls", "shared_execution_calls", "sealed",
                      "terminal_reason", "external_exit", "first_fault"):
            actual = deepcopy(specimen)
            actual["audit"][field] = changed(actual["audit"][field])
            self.assert_rejected(specimen, actual)
        actual = deepcopy(specimen)
        actual["outcome"]["selected_extent_sha256"] = "0" * 64
        self.assert_rejected(specimen, actual)
        actual = deepcopy(specimen)
        actual["audit"]["permissions"]["raw_reads"].append(0x1000)
        self.assert_rejected(specimen, actual)

    def test_all_thirty_five_capability_records_are_fully_compared(self):
        specimen = self.capabilities
        self.assertEqual(len(specimen["records"]), 35)
        self.assertIsNone(capability_oracle.compare(specimen, deepcopy(specimen)))
        for index, record in enumerate(specimen["records"]):
            with self.subTest(capability=record["id"], category="instance-accounting"):
                actual = deepcopy(specimen)
                actual["records"][index]["cpu_instances"] += 1
                self.assert_rejected(specimen, actual)
            with self.subTest(capability=record["id"], category="error-not-status-only"):
                actual = deepcopy(specimen)
                error = actual["records"][index]["error"]
                if error is None:
                    actual["records"][index]["error"] = {"code": "Fabricated", "address": None, "detail": "not expected"}
                else:
                    error["code"] += "_altered"
                self.assert_rejected(specimen, actual)
            if "audit" in record:
                for field in ("phase", "current_pc", "step_calls", "successful_retirements", "shared_execution_calls"):
                    actual = deepcopy(specimen)
                    actual["records"][index]["audit"][field] = changed(record["audit"][field])
                    self.assert_rejected(specimen, actual)
                actual = deepcopy(specimen)
                actual["records"][index]["after"]["ram"][0x109 - 0x80] ^= 1
                self.assert_rejected(specimen, actual)

    def test_prebus_refusal_schema_cannot_be_promoted_to_fake_bus_service(self):
        specimen = self.capabilities
        index = next(index for index, record in enumerate(specimen["records"])
                     if record["id"] == "data-write-after-seal")
        record = specimen["records"][index]
        attempts = record["audit"]["data_admission_refusals"]
        self.assertEqual(len(attempts), 1)
        attempt = attempts[0]
        self.assertEqual(attempt["classification"], "PreBusApiAdmissionRefusal")
        self.assertEqual(attempt["phase"], "Sealed")
        self.assertEqual(attempt["pc"], record["after"]["cpu"]["pc"])
        self.assertEqual((attempt["address"], attempt["width"], attempt["operation"],
                          attempt["requested_value"]), (0x117, 8, "Write", 0x55))
        self.assertIs(attempt["production_bus_called"], False)
        self.assertIs(attempt["serviced"], False)
        for field, value in attempt.items():
            if isinstance(value, dict):
                for error_field, error_value in value.items():
                    actual = deepcopy(specimen)
                    actual["records"][index]["audit"]["data_admission_refusals"][0][field][error_field] = changed(error_value)
                    self.assert_rejected(specimen, actual)
            else:
                actual = deepcopy(specimen)
                actual["records"][index]["audit"]["data_admission_refusals"][0][field] = changed(value)
                self.assert_rejected(specimen, actual)


if __name__ == "__main__":
    unittest.main()
